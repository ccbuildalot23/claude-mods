import { expect, mock, test } from 'claude-code/testing'

test('edits from the last reply replay one by one as diffs', async ($, on) => {
  mock.store(on)
  mock.clock(on, { now: Date.UTC(2026, 9, 22) })
  on('command.run', () => ({ text: 'engine' }))
  on('tool.call', () => ({ result: {} }))
  on('prompt.submit', (_, e) => ({ text: e.text }))
  on('ui.open', () => ({ value: { isPlaced: true } }))
  on('fs.read', () => Promise.reject(new Error('ENOENT')))
  await $.prompt.submit({ text: 'tidy the notes' } as never)
  await $.tool.call({ tool: 'Edit', file_path: '/w/a.md', old_string: 'old line', new_string: 'new line' })
  await $.tool.call({ tool: 'Write', file_path: '/w/b.md', content: 'fresh' })
  const band = await $.ui.mount({ plugin: 'replay-theater', component: 'AbovePrompt', props: { hasSurvey: false, isWorking: false, maxRows: 10, bodyColumns: 80, scroll: { offset: 0, bodyRows: 10 }, view: {} }, surface: 'terminal' })
  expect(await band.find({ type: 'Text', text: /2 file edits/ })).toBeDefined()
  await band.unmount()
  const r = await $.command.run({ command: 'replay', args: '' })
  expect(r.text ?? '').toContain('2 edits')
  const ui = await $.ui.mount({ plugin: 'replay-theater', component: 'Pane', requestId: 'replay-theater', props: { title: "x", isFocused: false, bodyColumns: 60, placement: "dock", scroll: { offset: 0, bodyRows: 40 }, view: {} }, surface: 'terminal' })
  expect(await ui.find({ type: 'Text', text: /Edit 1 of 2/ })).toBeDefined()
  expect((await ui.find({ type: 'Code' }))?.text ?? '').toContain('+new line')
  await ui.press({ key: 'next' })
  expect(await ui.find({ type: 'Text', text: /Edit 2 of 2: \/w\/b.md/ })).toBeDefined()
  await ui.unmount()
})
